CREATE TABLE IF NOT EXISTS epay_orders (
    out_trade_no VARCHAR(64) PRIMARY KEY,
    profile VARCHAR(32) NOT NULL,
    protocol VARCHAR(16) NOT NULL,
    gateway_id CHAR(32) NOT NULL,
    pid VARCHAR(12) NOT NULL,
    key_version VARCHAR(64) NOT NULL,
    config_fingerprint CHAR(64) NOT NULL,
    profile_config JSON NOT NULL,
    user_id INT NOT NULL,
    currency CHAR(3) NOT NULL,
    amount_cents BIGINT UNSIGNED NOT NULL,
    payment_type VARCHAR(32),
    trade_no VARCHAR(64),
    state VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    payment_id INT,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at DATETIME,
    UNIQUE KEY epay_gateway_trade (gateway_id, pid, trade_no),
    UNIQUE KEY epay_payment (payment_id),
    KEY epay_user_state (user_id, state, created_at),
    FOREIGN KEY (payment_id) REFERENCES pays_history(id),
    FOREIGN KEY (user_id) REFERENCES users(user_id),
    CHECK (currency = 'CNY'),
    CHECK (amount_cents > 0 AND amount_cents <= 9999999999),
    CHECK (state IN ('PENDING', 'PAID')),
    CHECK (protocol IN ('v1_md5', 'v2_rsa'))
) ENGINE=InnoDB DEFAULT CHARACTER SET ascii COLLATE ascii_bin;
